-- IBStreaming: catálogo por serviço de streaming
-- Execute uma única vez no Supabase SQL Editor antes de publicar esta versão.

create table if not exists public.streaming_services (
  id bigint generated by default as identity primary key,
  name text not null,
  slug text not null unique,
  active boolean not null default true,
  sort_order integer not null default 0,
  created_at timestamptz not null default now()
);

create table if not exists public.title_streaming_services (
  title_id bigint not null references public.titles(id) on delete cascade,
  service_id bigint not null references public.streaming_services(id) on delete cascade,
  created_at timestamptz not null default now(),
  primary key (title_id, service_id)
);

create index if not exists title_streaming_services_service_idx
  on public.title_streaming_services(service_id);

alter table public.streaming_services enable row level security;
alter table public.title_streaming_services enable row level security;

drop policy if exists "Authenticated users can read active streaming services" on public.streaming_services;
create policy "Authenticated users can read active streaming services"
  on public.streaming_services for select to authenticated
  using (active = true or exists (
    select 1 from public.accounts a where a.id = auth.uid() and a.role = 'admin'
  ));

drop policy if exists "Admins manage streaming services" on public.streaming_services;
create policy "Admins manage streaming services"
  on public.streaming_services for all to authenticated
  using (exists (select 1 from public.accounts a where a.id = auth.uid() and a.role = 'admin'))
  with check (exists (select 1 from public.accounts a where a.id = auth.uid() and a.role = 'admin'));

drop policy if exists "Authenticated users can read title service associations" on public.title_streaming_services;
create policy "Authenticated users can read title service associations"
  on public.title_streaming_services for select to authenticated
  using (exists (select 1 from public.streaming_services s where s.id = service_id and s.active = true)
    or exists (select 1 from public.accounts a where a.id = auth.uid() and a.role = 'admin'));

drop policy if exists "Admins manage title service associations" on public.title_streaming_services;
create policy "Admins manage title service associations"
  on public.title_streaming_services for all to authenticated
  using (exists (select 1 from public.accounts a where a.id = auth.uid() and a.role = 'admin'))
  with check (exists (select 1 from public.accounts a where a.id = auth.uid() and a.role = 'admin'));

